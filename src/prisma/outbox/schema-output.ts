import { createHash } from "node:crypto";
import {
  existsSync,
  lstatSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";

import { assert } from "@db21/toolkit/utils";

const markerName = ".db21-outbox-schema";
const marker = "Generated by @db21/toolkit/prisma/outbox/config v1\n";

const initializeOutput = (output: string): void => {
  if (existsSync(output)) {
    return;
  }

  const staging = mkdtempSync(join(dirname(output), ".db21-schema-root-"));

  try {
    writeFileSync(join(staging, markerName), marker, { flag: "wx" });

    try {
      renameSync(staging, output);
    } catch (error) {
      assert.true(
        error instanceof Error &&
          "code" in error &&
          ["EEXIST", "ENOTEMPTY", "ENOTDIR"].includes(String(error.code)),
        String(error),
      );
    }
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }
};

const assertRealDirectory = (directory: string): void => {
  const parent = dirname(directory);

  if (parent !== directory) {
    assertRealDirectory(parent);
  }

  mkdirSync(directory, { recursive: true });
  assert.true(
    lstatSync(directory).isDirectory() &&
      !lstatSync(directory).isSymbolicLink(),
    "Generated schema paths must not contain symlinks.",
  );
};

const assertGeneration = (
  directory: string,
  expected: Map<string, string>,
  prefix = "",
): void => {
  assert.true(
    lstatSync(directory).isDirectory() &&
      !lstatSync(directory).isSymbolicLink(),
    "Generated schema must be a real directory.",
  );

  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const name = join(prefix, entry.name);
    const path = join(directory, entry.name);

    assert.false(
      entry.isSymbolicLink(),
      "Generated schema must not contain symlinks.",
    );

    if (entry.isDirectory()) {
      assertGeneration(path, expected, name);
    } else {
      assert.true(
        entry.isFile() && expected.has(name),
        "Generated schema contains unexpected user files; refusing to reuse it.",
      );
      assert.true(
        readFileSync(path, "utf8") === expected.get(name),
        "Generated schema was modified; refusing to overwrite it.",
      );
      expected.delete(name);
    }
  }
};

const verifySnapshot = (
  directory: string,
  files: Map<string, string>,
): void => {
  const expected = new Map(files);

  assertGeneration(directory, expected);
  assert.true(expected.size === 0, "Generated schema snapshot is incomplete.");
};

/**
 * Publishes immutable content-addressed schema snapshots without partial reads.
 * @param output Dedicated helper-owned output root.
 * @param files Assembled relative schema paths and content.
 * @returns Complete schema snapshot directory.
 */
export const publishSchema = (
  output: string,
  files: Map<string, string>,
): string => {
  assertRealDirectory(dirname(output));

  initializeOutput(output);

  assert.true(
    lstatSync(output).isDirectory() && !lstatSync(output).isSymbolicLink(),
    "Output must be a dedicated generated directory.",
  );
  assert.true(
    lstatSync(join(output, markerName)).isFile() &&
      !lstatSync(join(output, markerName)).isSymbolicLink(),
    "Generated schema ownership marker must be a regular file.",
  );
  assert.true(
    readFileSync(join(output, markerName), "utf8") === marker,
    "Output directory is not owned by the schema assembler.",
  );

  const digest = createHash("sha256")
    .update(
      JSON.stringify([...files].toSorted(([a], [b]) => a.localeCompare(b))),
    )
    .digest("hex");
  const target = join(output, digest);

  if (existsSync(target)) {
    verifySnapshot(target, files);

    return target;
  }

  const staging = mkdtempSync(join(output, ".staging-"));

  try {
    for (const [name, content] of files) {
      const file = join(staging, name);

      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, content, { flag: "wx" });
    }

    try {
      renameSync(staging, target);
    } catch (error) {
      assert.true(
        error instanceof Error &&
          "code" in error &&
          ["EEXIST", "ENOTEMPTY"].includes(String(error.code)),
        String(error),
      );
    }

    verifySnapshot(target, files);
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }

  return target;
};
